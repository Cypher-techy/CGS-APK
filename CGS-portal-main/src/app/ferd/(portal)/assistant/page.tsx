import { PageHeader } from "@/components/ui";
import { adminConfigured } from "@/lib/supabase/admin";
import { ASSISTANT_LIMITS, assistantConfig } from "@/modules/ferd/assistant";
import { AssistantChat } from "@/modules/ferd/AssistantChat";
import { requireModule } from "@/modules/ferd/portal";

/** AI study assistant, grounded in the portal material the viewer is allowed to read. */
export default async function FerdAssistantPage() {
  const { department, moduleLabel } = await requireModule("assistant");
  const available = assistantConfig().configured && adminConfigured();
  return (
    <>
      <PageHeader title={moduleLabel} description={`Explanations, summaries, practice questions and revision plans for ${department.name}.`} />
      {available ? (
        <AssistantChat departmentName={department.name} maxTurns={ASSISTANT_LIMITS.maxTurns} maxChars={ASSISTANT_LIMITS.maxMessageChars} />
      ) : (
        <p className="alert alert-warning">The study assistant is not set up on this server yet. It will appear here once FERD configures it.</p>
      )}
      <ul className="mt-4 list-disc space-y-1 pl-5 text-xs text-muted-grey">
        <li>Answers are generated by an AI model and can be wrong. Check anything important against your notes or with your lecturer.</li>
        <li>The assistant only reads material published on this portal that your account can open. It cannot read locked premium items, uploaded PDF files or anything outside the portal.</li>
        <li>It marks what comes from your department&apos;s material and what is general knowledge.</li>
        <li>You can ask up to {ASSISTANT_LIMITS.perDay} questions a day. Your questions are sent to the AI provider to produce the answer and are not stored by FERD.</li>
      </ul>
    </>
  );
}
